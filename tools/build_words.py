PRESENT = {'e': ['եմ','ես','է','ենք','էք','են'], 'a': ['ամ','աս','այ','անք','աք','ան'], 'i': ['իմ','իս','ի','ինք','իք','ին']}
PAST = {'e': ['եցի','եցիր','եց','եցինք','եցիք','եցին'], 'a': ['ացի','ացիր','աց','ացինք','ացիք','ացին'], 'i': ['եցայ','եցար','եցաւ','եցանք','եցաք','եցան']}
VOW = set('աեէըիոօ')

def written_vowel_groups(w):
    # ու and իւ count as one vowel; ւ after another vowel is a consonant (v)
    n, i = 0, 0
    while i < len(w):
        c = w[i]
        if c in VOW:
            n += 1
            if i + 1 < len(w) and w[i+1] == 'ւ' and c in 'ոի':
                i += 1
        i += 1
    return n

def lead_consonants(w):
    k = 0
    for c in w:
        if c in VOW: break
        k += 1
    return k

def trail_consonants(w):
    k = 0
    for c in reversed(w):
        if c in VOW: break
        k += 1
    return k

