NO_PLURAL = {'ընտանիք', 'ժողովուրդ', 'կուրծք', 'ծրագիր', 'բանակում'}

def stem_for_suffix(w):
    # silent final յ drops before endings: շուկայ -> շուկան, շուկաներ
    return w[:-1] if w.endswith('այ') or w.endswith('ոյ') else w

def definite(w):
    if w.endswith('այ'):
        return w[:-1] + 'ն'
    return w + ('ն' if w[-1] in VOW else 'ը')

def plural(w):
    if w in PLURAL_EXC: return PLURAL_EXC[w]
    if w in NO_PLURAL or w.endswith('ութիւն'): return None
    if w[-1] == 'ռ': return None
    s = stem_for_suffix(w)
    if written_vowel_groups(w) == 1 and lead_consonants(w) <= 1 and trail_consonants(w) <= 2:
        return s + 'եր'
    return s + 'ներ'

def plural_definite(p):
    return p + 'ը' if not p.endswith('իկ') and not p.endswith('աք') else p + 'ը'

out = []
def add(*ws):
    for w in ws:
        if w: out.append(w)

for w in PLAIN.split():
    add(w)
for w in NOUNS.split():
    add(w, definite(w))
    p = plural(w)
    if p: add(p, plural_definite(p))
for w in MASS.split():
    add(w, definite(w))
for item in VERBS.split():
    inf, cls = item.split(':')
    irregular_past = cls.endswith('!')
    cls = cls.rstrip('!')
    add(inf)
    stem = inf[:-2]
    for suf in PRESENT[cls]: add(stem + suf)
    if not irregular_past:
        for suf in PAST[cls]: add(stem + suf)

